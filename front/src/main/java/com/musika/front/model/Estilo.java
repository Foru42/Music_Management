package com.musika.front.model;

public class Estilo {

    private Integer id;
    private String nombre;

    public Estilo() {

    }

    public void setId(Integer id) {
        this.id = id;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    public Integer getId() {
        return id;
    }

    public String getNombre() {
        return nombre;
    }

}
