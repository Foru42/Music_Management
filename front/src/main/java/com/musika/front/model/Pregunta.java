package com.musika.front.model;

public class Pregunta {

    private Integer id;
    private String texto;

    public Pregunta() {

    }

    public Integer getId() {
        return id;
    }

    public String getTexto() {
        return texto;
    }

    public void setId(Integer id) {
        this.id = id;
    }

    public void setTexto(String texto) {
        this.texto = texto;
    }

}
